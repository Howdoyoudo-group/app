/** Look up the image for a given industry + stage title. Returns undefined if not found. */
export const getStageImage = (industry: string, stageTitle: string): string | undefined => {
  const slug = industry.toLowerCase();
  const stages = careerStageImages[slug];
  if (!stages) return undefined;
  return stages[stageTitle.toLowerCase()];
};
